// Copies the component library source into the skill's copy-in fallback (assets/kit).
import { cpSync, rmSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dest = resolve(root, "skill/common-dashboard/assets/kit");
rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
cpSync(resolve(root, "packages/ui/src"), resolve(dest, "src"), { recursive: true });
const css = ["tokens.css", "components.css"].map((f) => readFileSync(resolve(root, "packages/ui/src/styles", f), "utf8")).join("\n");
writeFileSync(resolve(dest, "styles.css"), css);
const version = JSON.parse(readFileSync(resolve(root, "packages/ui/package.json"), "utf8")).version;
writeFileSync(resolve(dest, "README.md"), `# dashboard-kit copy-in (v${version})\n\nCopy this folder into a project (e.g. src/dashboard-kit/) when @dashboard-kit/ui cannot be installed.\n\n- Import \`./styles.css\` once, and \`./src/index\` for components.\n- Peer deps: react >= 18, react-dom >= 18. No other dependencies.\n- Do not edit these files per client; theme via ClientTheme.\n- Generated by scripts/sync-skill.mjs. Source of truth: packages/ui.\n`);
console.log("synced kit v" + version);
